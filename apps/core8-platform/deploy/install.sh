#!/usr/bin/env bash
# One-shot installer for a fresh Hostinger "Docker on Ubuntu 24.04" VPS.
#   curl -fsSL https://raw.githubusercontent.com/V1P3eR1/Core8-AI/feature/social-manager/apps/core8-platform/deploy/install.sh | DOMAIN=srv2179387.hstgr.cloud bash
# Re-running is safe: it pulls the latest code and rebuilds. Secrets in .env.production are never overwritten.
set -euo pipefail
DOMAIN="${DOMAIN:?set DOMAIN=your.host.name}"
BRANCH="${BRANCH:-feature/social-manager}"
ROOT="${ROOT:-/opt/core8}"
APP="$ROOT/apps/core8-platform"

echo "==> Core8 install  domain=$DOMAIN branch=$BRANCH root=$ROOT"
command -v docker >/dev/null || { echo "docker missing — use Hostinger's Docker template or install docker first"; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "docker compose plugin missing"; exit 1; }
command -v git >/dev/null || (apt-get update -qq && apt-get install -y -qq git)

if [ -d "$ROOT/.git" ]; then
  git -C "$ROOT" fetch -q origin && git -C "$ROOT" checkout -q "$BRANCH" && git -C "$ROOT" pull -q
else
  git clone -q --branch "$BRANCH" https://github.com/V1P3eR1/Core8-AI.git "$ROOT"
fi

ENV="$APP/backend/.env.production"
if [ ! -f "$ENV" ]; then
  echo "==> creating $ENV with generated secrets (ANTHROPIC/META keys left EMPTY)"
  gen() { tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1"; }
  FERNET=$(docker run --rm python:3.12-slim python -c "import base64,os;print(base64.urlsafe_b64encode(os.urandom(32)).decode())")
  cat > "$ENV" <<ENVEOF
# Generated by deploy/install.sh on $(date -u +%FT%TZ) — fill the empty keys with nano, then: docker compose ... up -d
ANTHROPIC_API_KEY=
JWT_SECRET=$(gen 64)
JWT_ACCESS_TTL_MINUTES=15
JWT_REFRESH_TTL_DAYS=7
BEARER_TOKEN=$(gen 48)
APPROVAL_MODE=smart
META_APP_ID=
META_APP_SECRET=
IG_TOKEN_ENC_KEY=$FERNET
GEMINI_API_KEY=
SOCIAL_TIMEZONE=Asia/Jerusalem
SOCIAL_INSTAGRAM_MODE=mock
SOCIAL_LLM_MODE=auto
SOCIAL_LLM_MODEL=claude-sonnet-4-5
SOCIAL_AI_DAILY_TOKEN_BUDGET=400000
SOCIAL_RESEARCH_MODE=auto
SOCIAL_WORKER_POLL_SECONDS=15
SOCIAL_MEDIA_SIGNING_KEY=$(gen 48)
SOCIAL_MEDIA_URL_TTL_SECONDS=7200
SOCIAL_MAX_UPLOAD_MB=300
SOCIAL_LEAD_WEBHOOK_TOKEN=$(gen 40)
SOCIAL_SEED_DEMO=true
ENVEOF
  chmod 600 "$ENV"
else
  echo "==> $ENV exists — keeping it"
fi

# firewall: only 22/80/443
if command -v ufw >/dev/null; then ufw allow 22/tcp >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null; ufw --force enable >/dev/null || true; fi

cd "$APP"
export DOMAIN
# Shared network for other services behind this Caddy; extra site files live in deploy/sites/.
docker network inspect core8-edge >/dev/null 2>&1 || docker network create core8-edge >/dev/null
mkdir -p deploy/sites
docker compose -f deploy/docker-compose.vps.yml up -d --build
echo
echo "==> done. Dashboard: https://$DOMAIN/social   (first visit creates the admin user)"
echo "    logs:    cd $APP && DOMAIN=$DOMAIN docker compose -f deploy/docker-compose.vps.yml logs -f --tail=100"
echo "    secrets: nano $ENV   then re-run this script"
